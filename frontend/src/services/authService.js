import api from './api'
export const login = (data) => api.post('/auth/login', data)
export const register = (data) => api.post('/auth/register', data)
export const getMe = () => api.get('/auth/me')
export const updateMe = (data) => api.put('/auth/me', data)
export const forgotPassword = (email) => api.post('/auth/forgot-password', { email })
export const resetPassword = (token, password) => api.post(`/auth/reset-password/${token}`, { password })
export const updateFarmLocation = (lat, lng) => api.put('/auth/location', { lat, lng })
// Invitaciones a la finca (el token llega por correo)
export const getInvitation = (token) => api.get(`/auth/invitation/${token}`)
export const acceptInvitation = (token, password) => api.post(`/auth/accept-invitation/${token}`, { password })